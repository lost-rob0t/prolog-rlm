test(execution_ledger_records_true_nested_depth_and_parent) :-
    model_response(root, 2, 1, RootResponse),
    model_response(child, 3, 1, ChildResponse),
    model_response(grandchild, 5, 2, GrandchildResponse),
    empty_exec_state(S0),
    rlm_plan:record_model_response(RootResponse, fake, S0, S1),
    rlm_plan:child_trace_state(nested_rlm_model, S1, ChildStart),
    rlm_plan:record_model_response(ChildResponse, fake, ChildStart, S2),
    rlm_plan:child_trace_state(nested_rlm_model, S2, GrandchildStart),
    rlm_plan:record_model_response(GrandchildResponse,
                                   fake,
                                   GrandchildStart,
                                   S3),
    rlm_plan:finalize_execution(final(done, S3), ok(Result)),
    Result.model_events = [RootEvent,ChildEvent,GrandchildEvent],
    assertion(RootEvent.sequence =:= 1),
    assertion(RootEvent.id == plan_model_1),
    assertion(RootEvent.parent == root_planner),
    assertion(RootEvent.depth =:= 0),
    assertion(RootEvent.reason == direct_plan_model),
    assertion(RootEvent.provider == fake),
    assertion(ChildEvent.sequence =:= 2),
    assertion(ChildEvent.id == plan_model_2),
    assertion(ChildEvent.parent == plan_model_1),
    assertion(ChildEvent.depth =:= 1),
    assertion(ChildEvent.reason == nested_rlm_model),
    assertion(GrandchildEvent.sequence =:= 3),
    assertion(GrandchildEvent.id == plan_model_3),
    assertion(GrandchildEvent.parent == plan_model_2),
    assertion(GrandchildEvent.depth =:= 2),
    assertion(GrandchildEvent.reason == nested_rlm_model),
    assertion(Result.model_responses ==
              [RootResponse,ChildResponse,GrandchildResponse]).

test(retry_scope_preserves_each_model_event_across_restore) :-
    model_response(first_attempt, 2, 1, R1),
    model_response(second_attempt, 3, 1, R2),
    empty_exec_state(S0),
    rlm_plan:trace_context(S0, ParentTrace),
    rlm_plan:child_trace_state(retry_model, S0, Attempt1),
    rlm_plan:record_model_response(R1, fake, Attempt1, S1),
    rlm_plan:restore_scope(S1, vars{}, ParentTrace, RetryBase),
    rlm_plan:child_trace_state(retry_model, RetryBase, Attempt2),
    rlm_plan:record_model_response(R2, fake, Attempt2, S2),
    rlm_plan:finalize_execution(final(done, S2), ok(Result)),
    Result.model_events = [E1,E2],
    assertion(E1.sequence =:= 1),
    assertion(E2.sequence =:= 2),
    assertion(E1.reason == retry_model),
    assertion(E2.reason == retry_model),
    assertion(E1.depth =:= 1),
    assertion(E2.depth =:= 1),
    assertion(E1.parent == root_planner),
    assertion(E2.parent == root_planner),
    assertion(Result.model_responses == [R1,R2]).

test(completion_uses_authoritative_nested_event_ledger) :-
    model_response(r1, 2, 1, R1),
    model_response(r2, 3, 1, R2),
    model_response(r3, 5, 2, R3),
    planner_result(Planner),
    PlanEvents = [
        plan_model_event{sequence:1,
                         id:plan_model_1,
                         parent:root_planner,
                         depth:0,
                         reason:direct_plan_model,
                         provider:fake,
                         response:R1},
        plan_model_event{sequence:2,
                         id:plan_model_2,
                         parent:plan_model_1,
                         depth:1,
                         reason:nested_rlm_model,
                         provider:fake,
                         response:R2},
        plan_model_event{sequence:3,
                         id:plan_model_3,
                         parent:plan_model_2,
                         depth:2,
                         reason:nested_rlm_model,
                         provider:fake,
                         response:R3}
    ],
    Result = plan_result{value:done,
                         vars:vars{},
                         transitions:[],
                         model_responses:[R1,R2,R3],
                         model_events:PlanEvents},
    rlm_completion:completion_finish(ok,
                                     Planner,
                                     plan([final(literal(done))]),
                                     Result,
                                     recursion_stats{},
                                     [],
                                     usage_summary{model_calls:4,
                                                   prompt_tokens:11,
                                                   completion_tokens:5,
                                                   total_tokens:16,
                                                   cost_usd:0.0,
                                                   cost_known:true,
                                                   tokens_known:true},
                                     ok(Completion)),
    Completion.trajectory.events = [Root,E1,E2,E3],
    assertion(Root.id == root_planner),
    assertion(E1.id == plan_model_1),
    assertion(E1.parent == root_planner),
    assertion(E1.depth =:= 0),
    assertion(E2.id == plan_model_2),
    assertion(E2.parent == plan_model_1),
    assertion(E2.depth =:= 1),
    assertion(E3.id == plan_model_3),
    assertion(E3.parent == plan_model_2),
    assertion(E3.depth =:= 2),
    assertion(E1.provider == fake),
    assertion(E2.selected_model == test_model),
    assertion(E3.http_status =:= 200),
    assertion(E3.usage.total_tokens =:= 7).

test(authoritative_event_order_is_not_reconstructed_from_vars) :-
    model_response(r1, 1, 1, R1),
    model_response(r2, 1, 1, R2),
    planner_result(Planner),
    PlanEvents = [
        plan_model_event{sequence:1,
                         id:first,
                         parent:root_planner,
                         depth:1,
                         reason:retry_attempt,
                         provider:fake,
                         response:R1},
        plan_model_event{sequence:2,
                         id:second,
                         parent:first,
                         depth:1,
                         reason:retry_attempt,
                         provider:fake,
                         response:R2}
    ],
    Result = plan_result{value:done,
                         vars:vars{only_visible:R2},
                         transitions:[],
                         model_responses:[R1,R2],
                         model_events:PlanEvents},
    rlm_completion:completion_finish(ok,
                                     Planner,
                                     plan([model(fake,
                                                 literal("ignored"),
                                                 _{},
                                                 only_visible),
                                           final(literal(done))]),
                                     Result,
                                     recursion_stats{},
                                     [],
                                     usage_summary{model_calls:3,
                                                   prompt_tokens:3,
                                                   completion_tokens:3,
                                                   total_tokens:6,
                                                   cost_usd:0.0,
                                                   cost_known:true,
                                                   tokens_known:true},
                                     ok(Completion)),
    Completion.trajectory.events = [_,First,Second],
    assertion(First.id == first),
    assertion(Second.id == second).

